-- Step 2: Update subjects primary key
UPDATE subjects SET id = (
  SELECT m.new_id FROM subject_id_map m WHERE m.old_id = subjects.id AND m.new_id IS NOT NULL
) WHERE id IN (SELECT old_id FROM subject_id_map WHERE new_id IS NOT NULL);

-- Step 3: Update grades references
UPDATE grades SET subject_id = (
  SELECT m.new_id FROM subject_id_map m WHERE m.old_id = grades.subject_id AND m.new_id IS NOT NULL
) WHERE subject_id IN (SELECT old_id FROM subject_id_map WHERE new_id IS NOT NULL);

-- Step 4: Update class_subjects references
UPDATE class_subjects SET subject_id = (
  SELECT m.new_id FROM subject_id_map m WHERE m.old_id = class_subjects.subject_id AND m.new_id IS NOT NULL
) WHERE subject_id IN (SELECT old_id FROM subject_id_map WHERE new_id IS NOT NULL);

-- Step 5: Mark as pending sync
UPDATE subjects SET sync_status = 'pending', updated_at = CURRENT_TIMESTAMP;
UPDATE grades SET sync_status = 'pending', updated_at = CURRENT_TIMESTAMP;
UPDATE class_subjects SET sync_status = 'pending', updated_at = CURRENT_TIMESTAMP;

-- Step 6: Clean up sync errors
DELETE FROM sync_queue WHERE status = 'error' AND table_name IN ('grades', 'subjects');

